// Pokémon Lakehouse service worker: works offline once opened.
// App files: network first (so updates arrive), cache as fallback.
// Artwork and fonts: cache first, since they never change.
const VERSION = "pl-v2";
const SHELL = ["./", "index.html", "styles.css", "app.js", "data/dex.json", "data/trainers.js", "manifest.webmanifest", "icons/icon-192.png", "icons/icon-512.png"];

self.addEventListener("install", e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== VERSION && k !== "pv-media").map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  const media = url.hostname === "raw.githubusercontent.com" || url.hostname.endsWith("gstatic.com") || url.hostname === "fonts.googleapis.com";
  if (media) {
    e.respondWith(caches.open("pv-media").then(async c => {
      const hit = await c.match(req);
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok || res.type === "opaque") c.put(req, res.clone());
      return res;
    }));
    return;
  }
  if (url.origin !== location.origin) return;
  e.respondWith(fetch(req).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(req, copy)); }
    return res;
  }).catch(() => caches.match(req, { ignoreSearch: true }).then(r => r || caches.match("index.html"))));
});
